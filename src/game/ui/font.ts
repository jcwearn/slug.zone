/**
 * A 5x7 bitmap font, drawn by hand.
 *
 * Not the page's Press Start 2P. Canvas text needs the webfont to have
 * finished loading before the first draw, and the HUD is drawn into a texture
 * on frame one -- so a font that arrives late gives you a HUD rendered in
 * Times New Roman that never corrects itself. A bitmap font has no load step
 * and cannot fall back.
 *
 * 5x7 is also simply the right size here. The render target is 320x200, so the
 * HUD has about forty pixels of height to work with, and anything with curves
 * turns to mush.
 */

