/** Anything not in the table renders as this, so a typo is visible not blank. */
const MISSING: number[] = [0x1f, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1f]

export const glyphWidth = (scale = 1) => GLYPH_WIDTH * scale
export const glyphHeight = (scale = 1) => GLYPH_HEIGHT * scale

/** Width in pixels of `text`, including the one-pixel gaps between glyphs. */
export function measureText(text: string, scale = 1, tracking = 1): number {
  if (text.length === 0) return 0
  return text.length * (GLYPH_WIDTH + tracking) * scale - tracking * scale
}

export function hasGlyph(ch: string): boolean {
  return ch.toUpperCase() in GLYPHS
}

/**
 * Draw `text` with its top-left at (x, y).
 *
 * Every pixel is a filled rect, so at scale 3 a glyph is 15x21 of hard square
 * pixels -- which is the point. Nothing here antialiases.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  colour: string,
  scale = 1,
  tracking = 1,
): void {
  ctx.fillStyle = colour
  let cursor = x
  for (const raw of text) {
    const rows = GLYPHS[raw.toUpperCase()] ?? MISSING
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      const bits = rows[row]
      for (let col = 0; col < GLYPH_WIDTH; col++) {
        if (bits & (1 << (GLYPH_WIDTH - 1 - col))) {
          ctx.fillRect(cursor + col * scale, y + row * scale, scale, scale)
        }
      }
    }
    cursor += (GLYPH_WIDTH + tracking) * scale
  }
}
